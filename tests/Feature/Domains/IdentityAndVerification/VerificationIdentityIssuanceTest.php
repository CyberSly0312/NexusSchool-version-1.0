<?php

declare(strict_types=1);

use App\Domains\AcademicCommunication\Application\AcademicCommunicationService;
use App\Domains\AcademicCommunication\Application\DTOs\GenerateDocumentData;
use App\Domains\AcademicCommunication\Domain\Contracts\DocumentRendererContract;
use App\Domains\AcademicCommunication\Domain\Enums\DocumentType;
use App\Domains\AcademicCommunication\Infrastructure\Models\AcademicDocumentTemplate;
use App\Domains\AcademicCommunication\Infrastructure\Models\PublicationPolicy;
use App\Domains\IdentityAndVerification\Application\Services\VerificationIdentityService;
use App\Domains\IdentityAndVerification\Domain\Exceptions\VerificationDocumentNotFoundException;
use App\Domains\IdentityAndVerification\Infrastructure\Models\VerificationIdentity;
use Tests\Support\FakeRenderer;

/**
 * Full communication context (template + policy) used to generate a real
 * document through the SPR-012 engine before issuing its verification identity.
 *
 * @return array{template: AcademicDocumentTemplate, policy: PublicationPolicy}
 */
function verificationIsolationContext(string $schoolId): array
{
    $template = AcademicDocumentTemplate::factory()
        ->forSchool($schoolId)
        ->ofType(DocumentType::ReportCard)
        ->create();

    $policy = PublicationPolicy::factory()
        ->forSchool($schoolId)
        ->ofType(DocumentType::ReportCard)
        ->create();

    return compact('template', 'policy');
}

function verificationIsolationData(
    string $schoolId,
    AcademicDocumentTemplate $template,
    PublicationPolicy $policy,
): GenerateDocumentData {
    return GenerateDocumentData::fromArray([
        'school_id' => $schoolId,
        'document_type' => DocumentType::ReportCard->value,
        'title' => 'Bulletin de test',
        'template_id' => $template->id,
        'policy_id' => $policy->id,
        'context' => ['student' => ['full_name' => 'Jean Dupont']],
    ]);
}

beforeEach(function (): void {
    $this->app->instance(DocumentRendererContract::class, new FakeRenderer());
    $this->communication = app(AcademicCommunicationService::class);
    $this->identities = app(VerificationIdentityService::class);
});

test('a document generated by the SPR-012 engine receives exactly one verification identity', function (): void {
    $school = makeTenant();
    $context = verificationIsolationContext($school);

    $document = $this->communication->generateDocument(
        verificationIsolationData($school, $context['template'], $context['policy']),
    );

    $token = $this->identities->issueForDocument($school, $document->getKey());
    $detail = $this->identities->resolve($token);

    expect($detail)->not->toBeNull();
    expect($detail->documentId)->toBe($document->getKey());
    expect($detail->schoolId)->toBe($school);
    expect($detail->documentStatus)->toBe('generated');
    expect($detail->publiclyVerifiable)->toBeFalse();

    expect(VerificationIdentity::forSchool($school)
        ->where('academic_document_id', $document->getKey())
        ->count())->toBe(1);
});

test('school A cannot issue an identity for a document generated by school B', function (): void {
    $schoolA = makeTenant();
    $schoolB = makeTenant();

    $contextB = verificationIsolationContext($schoolB);
    $documentB = $this->communication->generateDocument(
        verificationIsolationData($schoolB, $contextB['template'], $contextB['policy']),
    );

    $this->identities->issueForDocument($schoolA, $documentB->getKey());
})->throws(VerificationDocumentNotFoundException::class);

test('issuing twice for the same engine document is refused and the token keeps resolving', function (): void {
    $school = makeTenant();
    $context = verificationIsolationContext($school);

    $document = $this->communication->generateDocument(
        verificationIsolationData($school, $context['template'], $context['policy']),
    );

    $token = $this->identities->issueForDocument($school, $document->getKey());

    expect(fn (): string => $this->identities->issueForDocument($school, $document->getKey()))
        ->toThrow(App\Domains\IdentityAndVerification\Domain\Exceptions\VerificationIdentityAlreadyExistsException::class);

    expect($this->identities->resolve($token))->not->toBeNull();
    expect(VerificationIdentity::forSchool($school)->count())->toBe(1);
});
