<?php

declare(strict_types=1);

namespace App\Domains\AcademicCommunication\Infrastructure\Contracts;

use App\Domains\Academic\Infrastructure\Models\AcademicSubject;
use App\Domains\AcademicCommunication\Domain\Contracts\AssessmentContract;
use App\Domains\AcademicCommunication\Domain\References\AssessmentSummaryReference;
use App\Domains\AcademicCommunication\Domain\References\SubjectReference;
use App\Domains\Assessment\Infrastructure\Models\Assessment;
use App\Domains\Assessment\Infrastructure\Models\AssessmentScore;
use App\Domains\Enrollment\Infrastructure\Models\Enrollment;
use Illuminate\Support\Collection;

/**
 * Maps Assessment-domain models onto the AssessmentContract (SPR-012).
 *
 * Report cards are NOT generated by the Assessment engine: this adapter only
 * exposes the validated per-subject aggregates this engine renders.
 */
final class AssessmentAdapter implements AssessmentContract
{
    public function studentAssessmentSummaries(
        string $schoolId,
        int|string $studentId,
        int|string $yearId,
        int|string $termId,
    ): array {
        $enrollment = Enrollment::query()
            ->forSchool($schoolId)
            ->where('student_id', $studentId)
            ->where('academic_calendar_year_id', $yearId)
            ->orderByDesc('id')
            ->first();

        if ($enrollment === null) {
            return [];
        }

        $assessmentIds = Assessment::query()
            ->forSchool($schoolId)
            ->where('academic_calendar_year_id', $yearId)
            ->where('academic_calendar_term_id', $termId)
            ->whereIn('status', ['published', 'completed'])
            ->pluck('id');

        $rows = AssessmentScore::query()
            ->forSchool($schoolId)
            ->where('enrollment_id', $enrollment->getKey())
            ->whereIn('assessment_id', $assessmentIds)
            ->where('status', 'published')
            ->get()
            ->filter(fn (AssessmentScore $score): bool => $score->score !== null);

        $assessments = Assessment::query()
            ->forSchool($schoolId)
            ->whereIn('id', $rows->pluck('assessment_id')->unique())
            ->get()
            ->keyBy('id');

        $subjectIds = $assessments->pluck('academic_subject_id')->unique();
        $subjects = AcademicSubject::query()
            ->forSchool($schoolId)
            ->whereKey($subjectIds)
            ->get()
            ->keyBy('id');

        $scoresBySubject = $rows->groupBy(
            fn (AssessmentScore $score): int|string => (int) $assessments->get($score->assessment_id)?->academic_subject_id,
        );

        return $scoresBySubject
            ->map(fn (Collection $scores, int|string $subjectId): AssessmentSummaryReference => $this->aggregate(
                (int) $subjectId,
                $scores,
                $subjects,
            ))
            ->values()
            ->all();
    }

    /**
     * @param  Collection<int, AssessmentScore>  $scores
     * @param  Collection<int, \App\Domains\Academic\Infrastructure\Models\AcademicSubject>  $subjects
     */
    private function aggregate(int $subjectId, Collection $scores, Collection $subjects): AssessmentSummaryReference
    {
        $subject = $subjects->get($subjectId);

        $values = $scores->pluck('score')->map(fn (float $v): float => round($v, 2));

        return new AssessmentSummaryReference(
            subject: new SubjectReference(
                id: $subjectId,
                name: (string) ($subject?->name ?? 'Matière'),
                code: $subject?->code,
            ),
            assessmentCount: $scores->count(),
            bestScore: $values->max(),
            worstScore: $values->min(),
            average: round((float) $values->avg(), 2),
            passRate: round($values->filter(fn (float $v): bool => $v >= 10)->count() / max(1, $values->count()) * 100, 2),
        );
    }
}
